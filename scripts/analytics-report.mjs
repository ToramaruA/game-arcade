// Cloudflare Web Analytics から、サイト全体・ゲームごとのアクセスを集計し、
// GitHub の Issue「[REPORT] アクセスの記録」にコメントで投稿する（オーナーにメール通知が届く）。
// 使い方（GitHub Actions から）:
//   CF_ANALYTICS_TOKEN=... CLOUDFLARE_ACCOUNT_ID=... GITHUB_TOKEN=... GITHUB_REPOSITORY=owner/repo node scripts/analytics-report.mjs [--dry]
// 鍵の値はログに出さない。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE_URL } from './config.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const REPORT_TITLE = '[REPORT] アクセスの記録';
const DAY = 86400000;

export const QUERY = `query Report($account: string!, $start: Time!, $end: Time!) {
  viewer {
    accounts(filter: { accountTag: $account }) {
      byPath: rumPageloadEventsAdaptiveGroups(limit: 5000, filter: { datetime_geq: $start, datetime_leq: $end }, orderBy: [count_DESC]) {
        count
        sum { visits }
        dimensions { requestHost requestPath }
      }
      byRef: rumPageloadEventsAdaptiveGroups(limit: 200, filter: { datetime_geq: $start, datetime_leq: $end }, orderBy: [count_DESC]) {
        count
        dimensions { requestHost refererHost }
      }
    }
  }
}`;

// 期間：終わり＝今日の0時（UTC）、7日分。比較用に、その前の7日分
export function windows(now = new Date()) {
  const end = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  const cur = { start: new Date(end - 7 * DAY), end: new Date(end - 1) };
  const prev = { start: new Date(end - 14 * DAY), end: new Date(end - 7 * DAY - 1) };
  return { cur, prev };
}

// GraphQL の結果を、本番サイトのページだけに絞って集計する
export function summarize(data, host, games) {
  const acc = data?.viewer?.accounts?.[0] || { byPath: [], byRef: [] };
  const titles = Object.fromEntries(games.map((g) => [g.slug, g.title]));
  const perGame = {}; let pv = 0; let visits = 0; let top = 0;
  for (const r of acc.byPath || []) {
    if (r.dimensions.requestHost !== host) continue;
    pv += r.count; visits += r.sum?.visits || 0;
    const m = /^\/games\/([a-z0-9-]+)\/?/.exec(r.dimensions.requestPath || '');
    if (m && titles[m[1]]) {
      const g = perGame[m[1]] ||= { slug: m[1], title: titles[m[1]], pv: 0, visits: 0 };
      g.pv += r.count; g.visits += r.sum?.visits || 0;
    } else if ((r.dimensions.requestPath || '/') === '/' || r.dimensions.requestPath === '/index.html') top += r.count;
  }
  const refs = {};
  for (const r of acc.byRef || []) {
    if (r.dimensions.requestHost !== host) continue;
    const h = r.dimensions.refererHost || '（直接・不明）';
    if (h === host) continue; // サイト内の移動は除く
    refs[h] = (refs[h] || 0) + r.count;
  }
  return { pv, visits, top, games: Object.values(perGame).sort((a, b) => b.pv - a.pv), refs: Object.entries(refs).sort((a, b) => b[1] - a[1]) };
}

const fmt = (n) => n.toLocaleString('ja-JP');
const diff = (a, b) => (b ? `${a >= b ? '+' : ''}${Math.round(((a - b) / b) * 100)}%` : a ? '新規' : '—');
const md = (d) => `${d.getUTCMonth() + 1}/${d.getUTCDate()}`;

export function format({ cur, prev, win, games, reason, now = new Date(), mention = '' }) {
  const prevPv = Object.fromEntries(prev.games.map((g) => [g.slug, g.pv]));
  const lines = [];
  lines.push(`## アクセスの記録（${md(win.cur.start)}〜${md(win.cur.end)}）${reason ? `　${reason}` : ''}`);
  lines.push('');
  lines.push(`- **サイト全体**：PV ${fmt(cur.pv)}（先週 ${fmt(prev.pv)}、${diff(cur.pv, prev.pv)}）／訪問 ${fmt(cur.visits)}`);
  lines.push(`- **トップページ**：PV ${fmt(cur.top)}`);
  lines.push('');
  lines.push('| 順位 | ゲーム | PV | 先週比 | 訪問 | 公開から |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  const added = Object.fromEntries(games.map((g) => [g.slug, g.added]));
  const listed = games.filter((g) => g.listed !== false);
  const rows = [...cur.games];
  for (const g of listed) if (!rows.some((r) => r.slug === g.slug)) rows.push({ slug: g.slug, title: g.title, pv: 0, visits: 0 });
  rows.forEach((g, i) => {
    const days = added[g.slug] ? Math.floor((now - new Date(`${added[g.slug]}T00:00:00Z`)) / DAY) : null;
    lines.push(`| ${i + 1} | ${g.title} | ${fmt(g.pv)} | ${diff(g.pv, prevPv[g.slug] || 0)} | ${fmt(g.visits)} | ${days == null ? '—' : `${days}日`} |`);
  });
  lines.push('');
  const fresh = rows.filter((g) => added[g.slug] && now - new Date(`${added[g.slug]}T00:00:00Z`) <= 14 * DAY);
  if (fresh.length) lines.push(`- **公開2週間以内**：${fresh.map((g) => `${g.title}（PV ${fmt(g.pv)}）`).join('、')}`);
  if (cur.refs.length) lines.push(`- **来た所（上位5）**：${cur.refs.slice(0, 5).map(([h, n]) => `${h} ${fmt(n)}`).join('、')}`);
  lines.push('');
  lines.push('PV＝ページが開かれた回数、訪問＝別のサイトや直接入ってきた回数（Cloudflare Web Analytics。広告ブロックなどで数えられない分がある）。');
  if (mention) lines.push('', mention);
  lines.push('', '---', '_Generated by [Claude Code](https://claude.ai/code)_');
  return lines.join('\n');
}

async function cf(token, account, w) {
  const res = await fetch('https://api.cloudflare.com/client/v4/graphql', {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: QUERY, variables: { account, start: w.start.toISOString(), end: w.end.toISOString() } }),
  });
  const body = await res.json().catch(() => null);
  if (!res.ok || !body || body.errors?.length) {
    const msg = body?.errors?.map((e) => e.message).join(' / ') || `HTTP ${res.status}`;
    throw new Error(`Cloudflare の解析データを取れなかった：${msg}`);
  }
  return body.data;
}

async function gh(method, url, token, body) {
  const res = await fetch(`https://api.github.com${url}`, {
    method, headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json', 'Content-Type': 'application/json' },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) throw new Error(`GitHub ${method} ${url}: HTTP ${res.status}`);
  return res.json();
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const dry = process.argv.includes('--dry');
  const { CF_ANALYTICS_TOKEN: token, CLOUDFLARE_ACCOUNT_ID: account, GITHUB_TOKEN: ghToken, GITHUB_REPOSITORY: repo, REPORT_REASON: reason = '', REPORT_MENTION: mention = '' } = process.env;
  if (!token || !account) { console.error('CF_ANALYTICS_TOKEN と CLOUDFLARE_ACCOUNT_ID が必要（GitHub の Secrets に登録する）'); process.exit(1); }
  const games = JSON.parse(fs.readFileSync(path.join(ROOT, 'site', 'games', 'games.json'), 'utf8'));
  const host = new URL(SITE_URL).host;
  const win = windows();
  const cur = summarize(await cf(token, account, win.cur), host, games);
  const prev = summarize(await cf(token, account, win.prev), host, games);
  const text = format({ cur, prev, win, games, reason, mention });
  if (dry || !ghToken || !repo) { console.log(text); process.exit(0); }
  const issues = await gh('GET', `/repos/${repo}/issues?state=open&per_page=100`, ghToken);
  let issue = issues.find((i) => i.title === REPORT_TITLE && !i.pull_request);
  if (!issue) issue = await gh('POST', `/repos/${repo}/issues`, ghToken, { title: REPORT_TITLE, body: 'ゲームのアクセス数のまとめを、毎週月曜の朝にここへコメントします。この Issue は閉じずに置いておいてください。\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' });
  await gh('POST', `/repos/${repo}/issues/${issue.number}/comments`, ghToken, { body: text });
  console.log(`投稿した：#${issue.number}`);
}
