function build(w, h, fn) {
  const g = [];
  for (let y = 0; y < h; y++) {
    g.push([]);
    for (let x = 0; x < w; x++) g[y].push(x === 0 || y === 0 || x === w - 1 || y === h - 1 ? '#' : '.');
  }
  const put = (ch, ...pts) => pts.forEach(([x, y]) => { g[y][x] = ch; });
  const hl = (ch, y, x1, x2) => { for (let x = x1; x <= x2; x++) g[y][x] = ch; };
  const vl = (ch, x, y1, y2) => { for (let y = y1; y <= y2; y++) g[y][x] = ch; };
  const rect = (ch, x1, y1, x2, y2) => { for (let y = y1; y <= y2; y++) hl(ch, y, x1, x2); };
  fn({ put, hl, vl, rect });
  return g.map((r) => r.join(''));
}

