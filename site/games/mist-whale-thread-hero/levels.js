//        T 時計の門(閉じている間ふさぐ)  t 時計の橋(開いている間だけある)
// もの:  P 開始  E 灯台(出口)  * 星鈴  C 中継の灯  H 金のフック  h 星のフック(使うと消える)
//        L レバー1  l レバー2  G 鈴スイッチ1(敵や種を通すと鳴る)  g 鈴スイッチ2
//        K 大鐘(全部鳴らすと灯台が開く)  Q 時計の鐘  S 巨大な種  M 雲の舟
// 敵:    m 影蛾  a 鎧蜂  f 牙灯(左向き) F 牙灯(右向き)  n 海蛇の巣  e 糸喰い  R 夢のほつれ

export const ROWS = 14;

function build(w, fn) {
  const g = Array.from({ length: ROWS }, () => Array(w).fill('.'));
  const api = {
    // 地面：列 c0..c1 を行 top から下まで埋める
    g(c0, c1, top = 11, ch = '#') { for (let c = c0; c <= c1; c++) for (let r = top; r < ROWS; r++) g[r][c] = ch; },
    // 横一列
    f(c0, c1, r, ch) { for (let c = c0; c <= c1; c++) g[r][c] = ch; },
    // 縦一列
    v(c, r0, r1, ch) { for (let r = r0; r <= r1; r++) g[r][c] = ch; },
    p(c, r, ch) { g[r][c] = ch; },
  };
  fn(api);
  return g.map((row) => row.join(''));
}

