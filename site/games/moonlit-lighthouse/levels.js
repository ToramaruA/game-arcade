// 波の文字列を読み取る
export function parseWave(str) {
  return str.trim().split(/\s+/).map((g) => {
    const m = g.match(/^(\d):([a-zA-Z])(\d+)(?:\/([\d.]+))?(?:\*(\d))?(?:@([\d.]+))?$/);
    if (!m) throw new Error(`bad wave group: ${g}`);
    const type = ENEMY_CODES[m[2]];
    if (!type) throw new Error(`unknown enemy: ${m[2]}`);
    return { path: Number(m[1]), type, count: Number(m[3]), interval: m[4] ? Number(m[4]) : 1, pack: m[5] ? Number(m[5]) : 1, delay: m[6] ? Number(m[6]) : 0 };
  });
}

const BOSS_TYPES = new Set(['kingdeer', 'kingturtle', 'lord']);

// 潮替わり：波順を固定の別順（隣どうし入れ替え、最終波はそのまま）にし、入口（道0と道1）を交換する。ボスの道だけはそのまま。
export function tideOrder(n) {
  const order = [];
  for (let i = 0; i < n - 1; i += 2) {
    if (i + 1 < n - 1) order.push(i + 1, i); else order.push(i);
  }
  order.push(n - 1);
  return order;
}

export function wavesFor(nightIndex, mode = 'normal') {
  const night = NIGHTS[nightIndex];
  const parsed = night.waves.map(parseWave);
  if (mode !== 'tide') return parsed;
  const nPaths = night.paths.length;
  const swap = (p) => (nPaths < 2 ? p : p === 0 ? 1 : p === 1 ? 0 : p);
  // ボスは自分の「主の道」を変えない（護衛だけ入口が入れ替わる）
  return tideOrder(parsed.length).map((i) => parsed[i].map((g) => ({ ...g, path: BOSS_TYPES.has(g.type) ? g.path : swap(g.path) })));
}
